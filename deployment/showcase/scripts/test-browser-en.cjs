'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
let chromium;
try {({chromium}=require('playwright'));}
catch {({chromium}=require('C:/Users/seasu/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));}
const {createServer}=require('./serve.cjs');
const root=path.resolve(__dirname,'..'),qa=path.join(root,'qa/en');
fs.mkdirSync(qa,{recursive:true});
const checks=[],errors=[];
let browser,server;
const record=name=>{checks.push({name,passed:true});console.log('PASS '+name);};
(async()=>{
 server=createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const url='http://127.0.0.1:'+server.address().port;
 browser=await chromium.launch({headless:true,channel:'msedge'});
 const ctx=await browser.newContext({viewport:{width:1440,height:1000}}),page=await ctx.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url+'/en/');await page.locator('#toggle-play:not([disabled])').waitFor();
 await page.waitForFunction(()=>document.querySelector('#narration').readyState>=1);
 assert.equal(await page.locator('#slide-list button').count(),20);
 assert.equal(await page.locator('#total-duration').innerText(),'19:11 total');
 assert.equal(await page.evaluate(()=>document.querySelector('#narration').paused),true);
 assert.equal(await page.evaluate(()=>document.querySelector('#narration').currentTime),0);
 record('20 English slides, exact total rounded to 19:11, no autoplay on load');
 await page.screenshot({path:path.join(qa,'desktop.png'),fullPage:true});
 await page.locator('#toggle-play').click();
 await page.waitForFunction(()=>document.querySelector('#narration').currentTime>0.15&&!document.querySelector('#narration').paused);
 record('User click starts real MP3 playback');
 await page.locator('#toggle-play').click();
 const pausedAt=await page.evaluate(()=>document.querySelector('#narration').currentTime);
 await page.waitForTimeout(350);
 assert.ok(Math.abs(await page.evaluate(()=>document.querySelector('#narration').currentTime)-pausedAt)<.12);
 record('Pause preserves playback position');
 await page.locator('#toggle-play').click();
 await page.waitForFunction(t=>document.querySelector('#narration').currentTime>t+.15,pausedAt);
 await page.locator('#next').click();
 await page.waitForFunction(()=>document.querySelector('#page-count').textContent==='02 / 20'&&document.querySelector('#narration').currentTime>.1);
 record('Resume and next-slide playback work');
 await page.evaluate(()=>{const a=document.querySelector('#narration');a.currentTime=a.duration-.18;});
 await page.waitForFunction(()=>document.querySelector('#narration').ended);
 await page.locator('#toggle-play').click();
 await page.waitForTimeout(1700);
 assert.equal(await page.locator('#page-count').innerText(),'02 / 20');
 record('Pause during slide-ending delay prevents auto-advance');
 await page.locator('#toggle-play').click();
 await page.waitForFunction(()=>document.querySelector('#page-count').textContent==='03 / 20',null,{timeout:4000});
 await page.waitForFunction(()=>document.querySelector('#narration').currentTime>.1);
 record('Resume completes remaining 1.5 second tail and advances with narration');
 await page.locator('#toggle-play').click();
 await page.locator('#slide-list button').nth(13).click();
 assert.equal(await page.locator('#page-count').innerText(),'14 / 20');
 assert.equal(await page.evaluate(()=>document.querySelector('#narration').paused),true);
 assert.ok((await page.locator('#transcript-text').innerText()).includes('recruitment'));
 record('Contents navigation while paused updates slide, audio and English transcript');
 await page.locator('#mute').click();assert.equal(await page.evaluate(()=>document.querySelector('#narration').muted),true);
 await page.locator('#mute').click();
 await page.locator('#fullscreen').click();
 await page.waitForFunction(()=>!!document.fullscreenElement);
 await page.locator('#fullscreen').click();
 record('Mute toggle and full screen work');
 await page.locator('#slide-list button').last().click();
 assert.equal(await page.locator('#next').isDisabled(),true);
 await page.locator('#toggle-play').click();
 await page.waitForFunction(()=>!document.querySelector('#narration').paused);
 await page.evaluate(()=>{const a=document.querySelector('#narration');a.currentTime=a.duration-.12;});
 await page.waitForFunction(()=>document.querySelector('#toggle-play').textContent.includes('Replay'),null,{timeout:4000});
 assert.equal(await page.evaluate(()=>document.querySelector('#narration').paused),true);
 record('Last slide finishes without looping and offers Replay');
 await page.locator('#toggle-play').click();await page.waitForFunction(()=>document.querySelector('#page-count').textContent==='01 / 20');
 await page.locator('#toggle-play').click();
 const deck=await (await ctx.request.get(url+'/en/deck.json')).json();
 for(const slide of deck.slides){for(const route of [slide.image,slide.audio]){const r=await ctx.request.get(url+route);assert.equal(r.status(),200,route);}}
 for(const d of deck.downloads.filter(d=>d.url)){const r=await ctx.request.get(url+d.url);assert.equal(r.status(),200,d.url);}
 const range=await ctx.request.get(url+deck.slides[0].audio,{headers:{Range:'bytes=0-99'}});assert.equal(range.status(),206);assert.equal((await range.body()).length,100);
 record('All 20 PNGs, 20 MP3s, available downloads and audio byte ranges load');
 await page.setViewportSize({width:390,height:844});await page.goto(url+'/en/#slide-8');
 await page.locator('#toggle-play:not([disabled])').waitFor();
 assert.equal(await page.locator('#page-count').innerText(),'08 / 20');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:path.join(qa,'mobile.png'),fullPage:true});
 record('Mobile 390px layout has no horizontal overflow; direct slide links work');
 assert.deepEqual(errors,[]);record('No browser JavaScript errors');
 assert.equal(await page.locator('html').getAttribute('lang'),'en');
 assert.equal(await page.locator('a[href="/"]').count(),1);
 assert.equal(await page.locator('#download-list a').count(),3);
 record('English language, Mandarin version link and three English downloads');
 fs.writeFileSync(path.join(qa,'results.json'),JSON.stringify({passed:true,checks,errors,downloads:deck.downloads,totalSeconds:deck.totalSeconds},null,2));
})().catch(e=>{console.error(e.stack);fs.writeFileSync(path.join(qa,'results.json'),JSON.stringify({passed:false,checks,errors,error:e.message},null,2));process.exitCode=1}).finally(async()=>{if(browser)await browser.close();if(server)await new Promise(r=>server.close(r));});
